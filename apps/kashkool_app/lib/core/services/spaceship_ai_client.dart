import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../config/api_config.dart';
import '../network/network_client.dart';

/// The role whose academic voice the gateway should answer in.
enum KashkoolAiRole {
  student,
  teacher,
  center,
  secretary,
  parent,
  godMode,
}

/// Who wrote a single turn in a conversation.
enum AssistantTurnAuthor { learner, assistant }

/// One immutable turn of an assistant conversation.
///
/// Turns are sent to the gateway in order, so the answer keeps the thread's
/// context instead of treating every question as a brand new one.
class AssistantTurn {
  const AssistantTurn({required this.author, required this.text});

  const AssistantTurn.learner(this.text) : author = AssistantTurnAuthor.learner;

  const AssistantTurn.assistant(this.text)
      : author = AssistantTurnAuthor.assistant;

  final AssistantTurnAuthor author;
  final String text;

  String get _wireRole =>
      author == AssistantTurnAuthor.assistant ? 'assistant' : 'user';
}

/// A complete answer plus the follow-up prompts the model proposed for it.
class AssistantReply {
  const AssistantReply({required this.text, this.suggestions = const []});

  final String text;

  /// Follow-up questions generated by the model itself. Empty when the model
  /// offered none, never filled with canned strings.
  final List<String> suggestions;

  bool get isUsable => text.trim().isNotEmpty;
}

/// Why an assistant request failed, in terms the UI can act on.
enum AssistantFailure {
  /// The gateway is not reachable at all (not running, wrong address, no LAN).
  unreachable,

  /// The gateway accepted the connection but did not answer in time.
  timeout,

  /// The gateway answered with an error status.
  rejected,

  /// The gateway answered, but not with a usable completion.
  invalidResponse,
}

/// Raised instead of inventing an answer.
///
/// The previous implementation returned hardcoded Arabic templates on any
/// failure — including fabricated cash totals and balances. Fabricated money
/// figures are never acceptable in a production path, so a failure now
/// surfaces as an exception the UI renders as an error state with retry.
class AssistantException implements Exception {
  const AssistantException(this.failure, this.detail);

  final AssistantFailure failure;
  final String detail;

  /// Arabic sentence safe to show to a student, teacher, or parent.
  String get userMessage {
    switch (failure) {
      case AssistantFailure.unreachable:
        return 'تعذّر الوصول إلى محرك المساعدة. تأكد من الاتصال ثم أعد المحاولة.';
      case AssistantFailure.timeout:
        return 'المساعد استغرق وقتاً أطول من المتوقع. أعد المحاولة بعد لحظات.';
      case AssistantFailure.rejected:
        return 'المساعد مشغول الآن. أعد المحاولة بعد لحظات.';
      case AssistantFailure.invalidResponse:
        return 'لم يصل رد مكتمل من المساعد. أعد المحاولة.';
    }
  }

  @override
  String toString() => 'AssistantException($failure): $detail';
}

/// Client for the Kashkool Savior gateway.
///
/// The gateway speaks the OpenAI chat-completions dialect, so every role is
/// expressed as a system prompt sent to `/v1/chat/completions` with the
/// `kashkool-savior` meta model. The gateway picks the strongest healthy
/// upstream and fails over down the quality ladder.
class SpaceshipAiClient {
  SpaceshipAiClient(this._networkClient);

  final NetworkClient _networkClient;

  /// Kashkool Savior gateway base URL (platform-aware).
  static String get gatewayBaseUrl => ApiConfig.baseUrl;

  /// Default timeout for a gateway completion.
  ///
  /// Measured on the live arsenal: a single lesson turn takes 24–33 s (the
  /// strongest route is the local model), so this leaves real headroom.
  static const Duration defaultTimeout = Duration(seconds: 60);

  /// Timeout for the lightweight availability probe.
  static const Duration probeTimeout = Duration(seconds: 6);

  /// Turns kept from the conversation sent upstream. Older turns are dropped
  /// so a long lesson never overflows the model's context window.
  static const int maxContextTurns = 16;

  /// Marker the model uses to hand back follow-up prompts. ASCII so it survives
  /// every upstream's tokenizer and never collides with Arabic prose.
  static const String _suggestionsMarker = '[[SUGGESTIONS]]';

  /// Marker used to strip a leaked marker line out of the visible answer.
  static final RegExp _suggestionsLine =
      RegExp(r'\[\[SUGGESTIONS\]\]\s*[:\-]?\s*(.*)$', multiLine: true);

  /// Sends a full conversation and returns the next answer.
  Future<AssistantReply> chat({
    required KashkoolAiRole role,
    required List<AssistantTurn> turns,
    String subject = 'رياضيات وفيزياء الثانوية العامة',
    String grade = 'الصف الثالث الثانوي',
    String? tenantId,
    String? sessionId,
    Duration timeout = defaultTimeout,
    bool wantsSuggestions = true,
  }) async {
    if (turns.isEmpty) {
      throw const AssistantException(
        AssistantFailure.invalidResponse,
        'chat() called with an empty conversation',
      );
    }

    final history = _trimmed(turns);
    final body = <String, dynamic>{
      'model': ApiConfig.saviorModel,
      'temperature': 0.4,
      'messages': <Map<String, String>>[
        {
          'role': 'system',
          'content': _systemPrompt(
            role,
            subject,
            grade,
            wantsSuggestions: wantsSuggestions,
          ),
        },
        for (final turn in history)
          {'role': turn._wireRole, 'content': turn.text},
      ],
    };

    // Tenant/session travel as routing hints only; the gateway ignores them
    // when it has no per-tenant policy configured.
    if (tenantId != null && tenantId.isNotEmpty) {
      body['metadata'] = <String, String>{
        'tenant_id': tenantId,
        if (sessionId != null && sessionId.isNotEmpty) 'session_id': sessionId,
      };
    }

    final result = await _networkClient.post(
      '$gatewayBaseUrl/v1/chat/completions',
      body: body,
      config: RequestConfig(
        timeout: timeout,
        // The gateway already fails over between upstreams, so a client retry
        // would only double a 30 s wait. A failed turn surfaces to the learner
        // as a retry button instead.
        maxRetries: 0,
        requireAuth: false,
        idempotencyKey: 'ai-chat-${_mapRoleToString(role)}-${history.length}-'
            '${history.last.text.hashCode.abs()}',
      ),
    );

    if (result.isFailure) {
      throw _toException(result.error);
    }

    final data = result.data;
    if (data == null) {
      throw const AssistantException(
        AssistantFailure.invalidResponse,
        'Gateway returned an empty body',
      );
    }

    final content = _extractContent(data);
    if (content == null || content.trim().isEmpty) {
      throw const AssistantException(
        AssistantFailure.invalidResponse,
        'Gateway response had no choices[0].message.content',
      );
    }

    return _parseReply(content, wantsSuggestions: wantsSuggestions);
  }

  /// Single-question convenience wrapper around [chat].
  Future<String> ask({
    required KashkoolAiRole role,
    required String prompt,
    String subject = 'رياضيات وفيزياء الثانوية العامة',
    String grade = 'الصف الثالث الثانوي',
    String? tenantId,
    String? sessionId,
  }) async {
    final reply = await chat(
      role: role,
      turns: [AssistantTurn.learner(prompt)],
      subject: subject,
      grade: grade,
      tenantId: tenantId,
      sessionId: sessionId,
      wantsSuggestions: false,
    );
    return reply.text;
  }

  /// Streams a single answer.
  ///
  /// [NetworkClient] resolves complete responses, so the stream yields the one
  /// finished answer and lets the UI reveal it progressively.
  Stream<String> askStream({
    required KashkoolAiRole role,
    required String prompt,
    String subject = 'رياضيات وفيزياء الثانوية العامة',
    String grade = 'الصف الثالث الثانوي',
    String? tenantId,
    String? sessionId,
  }) async* {
    yield await ask(
      role: role,
      prompt: prompt,
      subject: subject,
      grade: grade,
      tenantId: tenantId,
      sessionId: sessionId,
    );
  }

  /// Probes `GET /health` so a screen can show the offline state before the
  /// learner types a full question and waits for a failure.
  Future<bool> checkAvailability({Duration timeout = probeTimeout}) async {
    final result = await _networkClient.get(
      '$gatewayBaseUrl/health',
      config: RequestConfig(
        timeout: timeout,
        maxRetries: 1,
        requireAuth: false,
      ),
    );

    if (result.isFailure || result.data == null) return false;
    final status = result.data!['status'];
    // Gateways that predate the `status` field still answer HTTP 200.
    return status is! String || status.toLowerCase() == 'ok';
  }

  List<AssistantTurn> _trimmed(List<AssistantTurn> turns) {
    final usable = turns
        .where((turn) => turn.text.trim().isNotEmpty)
        .toList(growable: false);
    if (usable.length <= maxContextTurns) return usable;
    return usable.sublist(usable.length - maxContextTurns);
  }

  AssistantException _toException(NetworkError? error) {
    final detail = error?.message ?? 'unknown network error';
    switch (error?.code) {
      case NetworkErrorCode.timeout:
        return AssistantException(AssistantFailure.timeout, detail);
      case NetworkErrorCode.connectionFailed:
        return AssistantException(AssistantFailure.unreachable, detail);
      case NetworkErrorCode.rateLimited:
      case NetworkErrorCode.serverError:
      case NetworkErrorCode.unauthorized:
      case NetworkErrorCode.forbidden:
      case NetworkErrorCode.notFound:
        return AssistantException(AssistantFailure.rejected, detail);
      case NetworkErrorCode.invalidResponse:
        return AssistantException(AssistantFailure.invalidResponse, detail);
      case NetworkErrorCode.cancelled:
      case NetworkErrorCode.unknown:
      case null:
        return AssistantException(AssistantFailure.unreachable, detail);
    }
  }

  /// Splits the visible answer from the follow-up prompts.
  AssistantReply _parseReply(String raw, {required bool wantsSuggestions}) {
    if (!wantsSuggestions) {
      return AssistantReply(text: raw.trim());
    }

    final matches = _suggestionsLine.allMatches(raw);
    if (matches.isEmpty) {
      return AssistantReply(text: raw.trim());
    }

    final last = matches.last;
    final suggestions = (last.group(1) ?? '')
        .split('|')
        .map((value) => value.replaceAll(RegExp(r'^[\s\-•*]+'), '').trim())
        .where((value) => value.isNotEmpty)
        .take(3)
        .toList(growable: false);

    final visible = raw.replaceRange(last.start, raw.length, '').trim();
    return AssistantReply(
      text: visible.isEmpty ? raw.trim() : visible,
      suggestions: suggestions,
    );
  }

  /// Reads `choices[0].message.content` from an OpenAI-style payload.
  static String? _extractContent(Map<String, dynamic> data) {
    final choices = data['choices'];
    if (choices is! List || choices.isEmpty) return null;
    final first = choices.first;
    if (first is! Map) return null;
    final message = first['message'];
    if (message is Map && message['content'] is String) {
      return message['content'] as String;
    }
    // Some upstreams answer with `text` instead of `message.content`.
    if (first['text'] is String) return first['text'] as String;
    return null;
  }

  /// Role-specific system prompt. These are academic instructions, not
  /// user-facing copy, and never mention the underlying model.
  static String _systemPrompt(
    KashkoolAiRole role,
    String subject,
    String grade, {
    bool wantsSuggestions = true,
  }) {
    const arabicRule = 'أجب بالعربية المصرية الواضحة. '
        'لا تذكر أنك نموذج ذكاء اصطناعي ولا تذكر اسم أي تقنية. '
        'التزم بالمنهج المصري.';

    final String persona;
    switch (role) {
      case KashkoolAiRole.student:
        persona = 'أنت المساعد الدراسي لطالب في $grade لمادة $subject. '
            'استخدم أسلوب سقراطي: اسأل سؤالاً واحداً في كل خطوة، '
            'شجّع المحاولة، وصحّح بلطف دون إعطاء الحل النهائي مباشرة.';
      case KashkoolAiRole.teacher:
        persona = 'أنت مساعد المعلم لمادة $subject لصف $grade. '
            'ولّد أسئلة MCQ ومقالية متدرجة المستوى مع نموذج الإجابة، '
            'وحدد الكود المعرفي لكل سؤال (تذكر/فهم/تطبيق/تحليل/تقييم/إبداع).';
      case KashkoolAiRole.center:
        persona = 'أنت مساعد إدارة المركز التعليمي. '
            'قدّم رؤى تشغيلية عن إشغال القاعات، تدفق الطلاب، وجدولة الحصص، '
            'مع توصيات عملية قابلة للتنفيذ.';
      case KashkoolAiRole.secretary:
        persona = 'أنت مساعد موظف الاستقبال. '
            'قدّم صياغات سريعة ومختصرة لرسائل التحصيل والإيصالات وتنبيهات '
            'المتأخرات، واذكر المبلغ المتبقي بوضوح بالجنيه المصري.';
      case KashkoolAiRole.parent:
        persona = 'أنت مرشد لولي الأمر. '
            'اكتب تقريراً أسبوعياً موجزاً ومتعاطفاً عن الحضور والمستوى '
            'الدراسي، مع نصيحة عملية واحدة لدعم الطالب في المنزل.';
      case KashkoolAiRole.godMode:
        persona = 'أنت محلل مالي وتشغيلي للمنصة. '
            'لخّص مؤشرات السيولة، رصد أي حركات غير معتادة، '
            'وقدّم ملاحظات تدقيق مختصرة قابلة للتنفيذ.';
    }

    final buffer = StringBuffer('$persona $arabicRule');
    buffer.write(' لا تخترع أرقاماً أو مبالغ أو درجات؛ استخدم فقط ما يذكره المستخدم، '
        'وإن لم تجد البيانات فاطلبها بوضوح.');
    if (wantsSuggestions) {
      buffer.write(' اختم ردك بسطر واحد فقط بالشكل التالي: '
          '$_suggestionsMarker اقتراح١ | اقتراح٢ | اقتراح٣'
          '، بحيث تكون الاقتراحات أسئلة قصيرة يطرحها المتعلم عليك بعد ذلك. '
          'لا تكتب أي شيء بعد هذا السطر.');
    }
    return buffer.toString();
  }

  static String _mapRoleToString(KashkoolAiRole role) {
    switch (role) {
      case KashkoolAiRole.student:
        return 'student';
      case KashkoolAiRole.teacher:
        return 'teacher';
      case KashkoolAiRole.center:
        return 'center';
      case KashkoolAiRole.secretary:
        return 'secretary';
      case KashkoolAiRole.parent:
        return 'parent';
      case KashkoolAiRole.godMode:
        return 'god_mode';
    }
  }
}

/// Riverpod provider for SpaceshipAiClient
final spaceshipAiClientProvider = Provider<SpaceshipAiClient>((ref) {
  final networkClient = ref.watch(networkClientProvider);
  return SpaceshipAiClient(networkClient);
});
