export function t(key: string, lang: AppLanguage): string {
  const dict = lang === AppLanguage.AR ? ar : en;
  return dict[key] ?? en[key] ?? key;
}

export function ledgerKindLabel(kindKey: string, lang: AppLanguage): string {
  switch (kindKey) {
    case LedgerKind.CASH_TOPUP:
      return t("cash_topup", lang);
    case LedgerKind.PARTIAL_INSTALLMENT:
      return t("partial_installment", lang);
    case LedgerKind.BOOK_RESERVATION:
      return t("book_reservation", lang);
    case LedgerKind.DISCOUNT:
      return t("teacher_discount", lang);
    case LedgerKind.SETTLEMENT:
      return t("run_settlement", lang);
    case LedgerKind.VOID_ENTRY:
      return t("void_entry", lang);
    default:
      return kindKey;
  }
}
