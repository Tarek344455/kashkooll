    fun t(key: String, lang: AppLanguage): String {
        val map = if (lang == AppLanguage.AR) ar else en
        return map[key] ?: en[key] ?: key
    }

    fun ledgerKindLabel(kindKey: String, lang: AppLanguage): String {
        val mapKey = when (kindKey) {
            LedgerKind.CASH_TOPUP.key -> "cash_topup"
            LedgerKind.PARTIAL_INSTALLMENT.key -> "partial_installment"
            LedgerKind.BOOK_RESERVATION.key -> "book_reservation"
            LedgerKind.DISCOUNT.key -> "teacher_discount"
            LedgerKind.SETTLEMENT.key -> "run_settlement"
            LedgerKind.VOID_ENTRY.key -> "void_entry"
            else -> return kindKey
        }
        return t(mapKey, lang)
    }

