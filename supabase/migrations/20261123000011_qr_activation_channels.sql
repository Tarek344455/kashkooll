-- Zero-Cost Onboarding: QR activation codes + expanded payment channels.
--
-- 1. Add qr_activation_code + qr_activated_at to profiles so the centre
--    secretary can activate a student/parent locally without SMS or email.
-- 2. Expand payment_channels.channel_type check to include Etisalat Cash,
--    Orange Cash, We Pay, and Cash Desk (direct center collection).
-- 3. Add index on qr_activation_code for fast lookup during activation.

-- ---------------------------------------------------------------------------
-- 1. profiles: QR activation columns
-- ---------------------------------------------------------------------------
alter table public.profiles
  add column if not exists qr_activation_code text;

alter table public.profiles
  add column if not exists qr_activated_at timestamptz;

create index if not exists profiles_qr_activation_idx
  on public.profiles (qr_activation_code)
  where qr_activated_at is null;

-- ---------------------------------------------------------------------------
-- 2. payment_channels: expand channel_type check constraint
--    PostgreSQL cannot ALTER a CHECK constraint in place, so we drop and
--    recreate it with the expanded list of allowed values.
-- ---------------------------------------------------------------------------
do $$
begin
  -- Drop the old constraint if it exists.
  if exists (
    select 1 from pg_constraint
    where conrelid = 'public.payment_channels'::regclass
      and conname = 'payment_channels_channel_type_check'
  ) then
    alter table public.payment_channels
      drop constraint payment_channels_channel_type_check;
  end if;

  -- Recreate with expanded list.
  alter table public.payment_channels
    add constraint payment_channels_channel_type_check
    check (channel_type in (
      'vodafone_cash',
      'etisalat_cash',
      'orange_cash',
      'we_pay',
      'insta_pay',
      'fawry',
      'cash',
      'cash_desk'
    ));
end
$$;

-- ---------------------------------------------------------------------------
-- 3. Comment on columns for documentation
-- ---------------------------------------------------------------------------
comment on column public.profiles.qr_activation_code is
  'One-time code generated by the centre secretary for local student activation (Zero-Cost onboarding).';

comment on column public.profiles.qr_activated_at is
  'Timestamp when the QR activation code was consumed; null means still valid.';